create extension if not exists pg_net;

-- ───────────── таблицы ─────────────

create table if not exists public.categories (
  id    text primary key,
  name  text not null,
  sort  int  not null default 0
);

create table if not exists public.products (
  id          text primary key,
  name        text not null,
  brand       text not null default '',
  cat         text not null references public.categories(id) on update cascade,
  price       int  not null check (price >= 0),
  old_price   int  check (old_price is null or old_price >= 0),
  pop         int  not null default 0,
  tag         text,
  color       text not null default '#8E86A8',
  spec        text not null default '',
  image_url   text,
  stock       int,                                   -- null = не отслеживаем остаток
  active      boolean not null default true,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- одна строка с настройками сайта
create table if not exists public.site_settings (
  id    int primary key default 1 check (id = 1),
  data  jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.customers (
  id          uuid primary key default gen_random_uuid(),
  phone       text not null unique,                  -- только цифры, 11 знаков: 77071234567
  name        text not null default '',
  notes       text not null default '',
  created_at  timestamptz not null default now()
);

create table if not exists public.orders (
  id            bigint generated by default as identity (start with 1001) primary key,
  kind          text not null default 'order' check (kind in ('order','preorder')),
  status        text not null default 'new'
                check (status in ('new','contacted','paid','shipped','done','canceled')),
  customer_id   uuid references public.customers(id) on delete set null,
  name          text not null,
  phone         text not null,
  items         jsonb not null default '[]'::jsonb,   -- [{id,name,price,qty}]
  request       text,                                 -- для предзаказа: что привезти
  subtotal      int not null default 0,
  discount      int not null default 0,
  total         int not null default 0,
  promo_code    text,
  manager_note  text not null default '',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists orders_created_idx  on public.orders (created_at desc);
create index if not exists orders_status_idx   on public.orders (status);
create index if not exists orders_customer_idx on public.orders (customer_id);

-- сотрудники с доступом в админку
create table if not exists public.staff (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  email       text not null,
  role        text not null default 'manager' check (role in ('admin','manager')),
  created_at  timestamptz not null default now()
);

-- секреты (токен Telegram-бота): закрыты от всех, кроме самой базы
create schema if not exists private;
create table if not exists private.secrets (
  key   text primary key,
  value text not null
);
revoke all on schema private from public, anon, authenticated;

-- ───────────── вспомогательные функции ─────────────

create or replace function public.is_staff() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid());
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.staff where user_id = auth.uid() and role = 'admin');
$$;

create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();
drop trigger if exists orders_touch on public.orders;
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();
drop trigger if exists settings_touch on public.site_settings;
create trigger settings_touch before update on public.site_settings
  for each row execute function public.touch_updated_at();

-- ───────────── оформление заказа с сайта ─────────────
-- Сайт не может писать в таблицы напрямую. Он вызывает эту функцию,
-- а она сама берёт цены из базы и считает скидку, поэтому подменить сумму нельзя.

create or replace function public.place_order(
  p_name    text,
  p_phone   text,
  p_items   jsonb default '[]'::jsonb,   -- [{"id":"aula-f75","qty":1}]
  p_promo   text  default null,
  p_request text  default null           -- текст предзаказа
) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_phone    text := regexp_replace(coalesce(p_phone,''), '\D', '', 'g');
  v_name     text := left(btrim(coalesce(p_name,'')), 100);
  v_request  text := nullif(left(btrim(coalesce(p_request,'')), 1000), '');
  v_kind     text;
  v_settings jsonb;
  v_promo    jsonb;
  v_items    jsonb := '[]'::jsonb;
  v_sub      int := 0;
  v_disc     int := 0;
  v_code     text := null;
  v_customer uuid;
  v_id       bigint;
  r          record;
begin
  if length(v_phone) = 10 then v_phone := '7' || v_phone; end if;
  if length(v_phone) = 11 and left(v_phone,1) = '8' then v_phone := '7' || substr(v_phone,2); end if;
  if v_name = '' or length(v_phone) < 10 or length(v_phone) > 15 then
    raise exception 'Укажите имя и телефон';
  end if;

  -- защита от спама: не больше 5 заявок с одного номера за 10 минут
  if (select count(*) from orders where phone = v_phone and created_at > now() - interval '10 minutes') >= 5 then
    raise exception 'Слишком много заявок, попробуйте позже';
  end if;

  if jsonb_typeof(p_items) = 'array' and jsonb_array_length(p_items) > 0 then
    v_kind := 'order';
    for r in
      select p.id, p.name, p.price, least(greatest(coalesce((x->>'qty')::int,1),1),99) as qty
      from jsonb_array_elements(p_items) x
      join products p on p.id = x->>'id' and p.active
    loop
      v_items := v_items || jsonb_build_object('id',r.id,'name',r.name,'price',r.price,'qty',r.qty);
      v_sub := v_sub + r.price * r.qty;
    end loop;
    if jsonb_array_length(v_items) = 0 then raise exception 'Товары не найдены'; end if;
  elsif v_request is not null then
    v_kind := 'preorder';
  else
    raise exception 'Пустой заказ';
  end if;

  select data into v_settings from site_settings where id = 1;
  v_promo := v_settings->'promo';
  if p_promo is not null and v_promo is not null
     and upper(btrim(p_promo)) = upper(v_promo->>'code')
     and now() <= (v_promo->>'until')::timestamptz then
    v_code := v_promo->>'code';
    v_disc := round(v_sub * (v_promo->>'percent')::numeric / 100);
  end if;

  insert into customers (phone, name) values (v_phone, v_name)
  on conflict (phone) do update set name = case when customers.name = '' then excluded.name else customers.name end
  returning id into v_customer;

  insert into orders (kind, customer_id, name, phone, items, request, subtotal, discount, total, promo_code)
  values (v_kind, v_customer, v_name, v_phone, v_items, v_request, v_sub, v_disc, v_sub - v_disc, v_code)
  returning id into v_id;

  return jsonb_build_object('id', v_id, 'subtotal', v_sub, 'discount', v_disc, 'total', v_sub - v_disc);
end $$;

revoke all on function public.place_order(text,text,jsonb,text,text) from public;
grant execute on function public.place_order(text,text,jsonb,text,text) to anon, authenticated;

-- ───────────── добавление сотрудника (только для админа) ─────────────
-- Сначала создайте пользователя: Authentication → Users → Add user.
-- Затем добавьте его в админке на вкладке «Сотрудники» по email.

create or replace function public.add_staff(p_email text, p_role text default 'manager') returns void
language plpgsql security definer set search_path = public as $$
declare v_uid uuid;
begin
  if not is_admin() then raise exception 'Только администратор может добавлять сотрудников'; end if;
  if p_role not in ('admin','manager') then raise exception 'Неизвестная роль'; end if;
  select id into v_uid from auth.users where lower(email) = lower(btrim(p_email));
  if v_uid is null then
    raise exception 'Пользователь % не найден. Создайте его в Supabase: Authentication → Users → Add user', p_email;
  end if;
  insert into staff (user_id, email, role) values (v_uid, lower(btrim(p_email)), p_role)
  on conflict (user_id) do update set role = excluded.role;
end $$;
revoke all on function public.add_staff(text,text) from public;
grant execute on function public.add_staff(text,text) to authenticated;

-- ───────────── уведомление о новом заказе в Telegram ─────────────
-- Включается, когда в private.secrets есть telegram_token и telegram_chat_id (см. README).

create or replace function public.notify_telegram() returns trigger
language plpgsql security definer set search_path = public, private as $$
declare
  v_token text; v_chat text; v_text text; v_lines text;
begin
  select value into v_token from private.secrets where key = 'telegram_token';
  select value into v_chat  from private.secrets where key = 'telegram_chat_id';
  if v_token is null or v_chat is null then return new; end if;

  if new.kind = 'preorder' then
    v_text := format(E'🆕 Предзаказ №%s\n%s, +%s\n\n%s', new.id, new.name, new.phone, new.request);
  else
    select string_agg(format('• %s × %s', x->>'name', x->>'qty'), E'\n') into v_lines
    from jsonb_array_elements(new.items) x;
    v_text := format(E'🛒 Заказ №%s\n%s, +%s\n\n%s\n\nИтого: %s ₸%s',
      new.id, new.name, new.phone, v_lines, replace(to_char(new.total, 'FM999,999,999'), ',', ' '),
      case when new.promo_code is not null then format(' (промокод %s)', new.promo_code) else '' end);
  end if;

  perform net.http_post(
    url     := format('https://api.telegram.org/bot%s/sendMessage', v_token),
    body    := jsonb_build_object('chat_id', v_chat, 'text', v_text),
    headers := '{"Content-Type":"application/json"}'::jsonb
  );
  return new;
exception when others then
  return new;   -- уведомление не должно ломать оформление заказа
end $$;

drop trigger if exists orders_notify on public.orders;
create trigger orders_notify after insert on public.orders
  for each row execute function public.notify_telegram();

